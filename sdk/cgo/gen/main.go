// Command gen writes include/urnetwork_sdk.def for the composed native library: the core SDK's
// .def entries and this directory's messaging exports, merged.
//
//	go run ./gen [-core <core sdk root>]      from sdk/cgo; the default core root is ../sdk
//	                                          beside this repository, where test.sh checks it out
//
// THE .def IS A PROMISE ABOUT THE LIBRARY. An MSVC consumer builds its import library from it, so a
// name it lacks is a link error at the consumer and a name the library does not export is one too.
// The library is the composition (compose.sh): the core SDK's cgo package main with the messaging
// half laid beside it. The core's generator writes the core's .def from the core's own surface;
// before the split it also picked up the messaging exports, because they sat in its directory. They
// sit here now, so this is the one place both halves are named together: the core's entries, read
// off the core's own generated .def, and every //export of this directory's hand-written files that
// is in a shipped build. The loopback harness (loopback_test_world.go, behind
// `//go:build urnet_message_loopback`) is in none and contributes nothing.
//
// The format is the core generator's: a comment line, LIBRARY and EXPORTS, then one tab-indented
// name per line, sorted and without duplicates. gen's tests hold the committed file to this
// output byte for byte, so a core pin that moved, or an export added here, is red until this is
// rerun.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/build/constraint"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

func main() {
	core := flag.String("core", filepath.Join("..", "..", "..", "sdk"), "the core SDK checkout (urnetwork/sdk at the pinned commit)")
	flag.Parse()
	def, counts, err := composedDef(*core, ".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join("include", "urnetwork_sdk.def"), def, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Printf("gen: include/urnetwork_sdk.def names %d exports: %d from the core's .def, %d messaging\n",
		counts.total, counts.core, counts.messaging)
}

// defCounts is how many names each half contributed.
type defCounts struct {
	core, messaging, total int
}

// The header the composed .def opens with.
const composedDefHeader = "; Code generated by sdk/cgo/gen from the core SDK's include/urnetwork_sdk.def and this directory's exports. DO NOT EDIT.\n" +
	"LIBRARY URnetworkSdk\nEXPORTS\n"

// composedDef answers the composed .def: the core .def under core/cgo/include, merged with the
// messaging exports of the hand-written files in dir.
func composedDef(core string, dir string) ([]byte, defCounts, error) {
	coreDef, err := os.ReadFile(filepath.Join(core, "cgo", "include", "urnetwork_sdk.def"))
	if err != nil {
		return nil, defCounts{}, fmt.Errorf("the core SDK's .def: %w", err)
	}
	coreNames, err := defEntries(string(coreDef))
	if err != nil {
		return nil, defCounts{}, fmt.Errorf("the core SDK's .def: %w", err)
	}
	messaging, err := messagingExports(dir)
	if err != nil {
		return nil, defCounts{}, err
	}
	if len(messaging) == 0 {
		return nil, defCounts{}, fmt.Errorf("%s holds no shipped //export at all", dir)
	}
	for _, name := range messaging {
		if slices.Contains(coreNames, name) {
			return nil, defCounts{}, fmt.Errorf("%s is exported here AND named by the core's .def: the core still carries the messaging half, or a name was claimed twice", name)
		}
	}
	names := append(slices.Clone(coreNames), messaging...)
	slices.Sort(names)
	names = slices.Compact(names)
	var b strings.Builder
	b.WriteString(composedDefHeader)
	for _, name := range names {
		b.WriteString("\t")
		b.WriteString(name)
		b.WriteString("\n")
	}
	return []byte(b.String()), defCounts{core: len(coreNames), messaging: len(messaging), total: len(names)}, nil
}

// defName is one export of a .def, as the core generator writes it.
var defName = regexp.MustCompile(`^\t(\w+)$`)

// defEntries reads the names a .def exports. It refuses a file that is not the generator's shape:
// a LIBRARY line naming URnetworkSdk, an EXPORTS line, and after it nothing but tab-indented names.
func defEntries(text string) ([]string, error) {
	text = strings.ReplaceAll(text, "\r\n", "\n")
	names := []string{}
	library, exports := false, false
	scanner := bufio.NewScanner(strings.NewReader(text))
	for scanner.Scan() {
		line := scanner.Text()
		switch {
		case strings.HasPrefix(line, ";") && !exports:
		case line == "LIBRARY URnetworkSdk" && !exports:
			library = true
		case line == "EXPORTS" && library && !exports:
			exports = true
		case exports:
			match := defName.FindStringSubmatch(line)
			if match == nil {
				return nil, fmt.Errorf("an EXPORTS line that is not a tab-indented name: %q", line)
			}
			names = append(names, match[1])
		default:
			return nil, fmt.Errorf("a line before EXPORTS that is not a comment or LIBRARY URnetworkSdk: %q", line)
		}
	}
	if !library || !exports {
		return nil, fmt.Errorf("no LIBRARY URnetworkSdk and EXPORTS header")
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("EXPORTS names nothing")
	}
	return names, nil
}

// exportDirective is the core generator's scan pattern, CRLF tolerant: on a CRLF checkout an
// anchored `$` after the name matches nothing, and every export would silently vanish.
var exportDirective = regexp.MustCompile(`(?m)^//export (\w+)[ \t\r]*$`)

// messagingExports answers the //export names of the hand-written .go files of dir that are in a
// shipped build, sorted. A file a compose laid here from the core (listed in dir/.composed) is the
// core's and is not read: its exports reach the .def through the core's own.
func messagingExports(dir string) ([]string, error) {
	composed := map[string]bool{}
	if record, err := os.ReadFile(filepath.Join(dir, ".composed")); err == nil {
		for _, line := range strings.Split(strings.ReplaceAll(string(record), "\r\n", "\n"), "\n") {
			if line != "" && !strings.HasPrefix(line, "#") {
				composed[line] = true
			}
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	names := []string{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || composed[name] {
			continue
		}
		source, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		if !inAnyShippedBuild(string(source)) {
			continue
		}
		for _, match := range exportDirective.FindAllStringSubmatch(string(source), -1) {
			names = append(names, match[1])
		}
	}
	slices.Sort(names)
	return slices.Compact(names), nil
}

// inAnyShippedBuild reports whether a source file is compiled into any library this repository
// ships. It is the core generator's function (urnetwork/sdk cgo/gen/gen.go), copied with its
// reasoning, because the question is the same here: manualExports-style scans read raw file bytes,
// so an //export inside a build-tag-gated file would reach the .def without it.
//
// THE QUESTION IT ASKS IS "IS THIS FILE IN ANY SHIPPED BUILD", not "is it in this one". A custom
// tag -- one no build passes -- is always false. A platform tag is evaluated BOTH ways and either
// answer counts, because the library ships for several platforms: a file gated on `//go:build !js`
// is in all of them and one gated on `//go:build js` is in the js build, and an evaluator that
// pinned the platform tags one way would drop one of those two.
func inAnyShippedBuild(source string) bool {
	for _, line := range strings.Split(source, "\n") {
		line = strings.TrimRight(line, "\r")
		if trimmed := strings.TrimSpace(line); trimmed != "" && !strings.HasPrefix(trimmed, "//") {
			// past the header, where a //go:build line may no longer appear
			return true
		}
		if !strings.HasPrefix(line, "//go:build ") {
			continue
		}
		expr, err := constraint.Parse(line)
		if err != nil {
			// an unparseable constraint is not a licence to publish the symbol
			return false
		}
		for _, platform := range []bool{true, false} {
			if expr.Eval(func(tag string) bool {
				switch tag {
				case "unix", "cgo", "gc":
					return platform
				}
				return (knownOS[tag] || knownArch[tag]) && platform
			}) {
				return true
			}
		}
		return false
	}
	return true
}

var knownOS = map[string]bool{
	"aix": true, "android": true, "darwin": true, "dragonfly": true, "freebsd": true,
	"hurd": true, "illumos": true, "ios": true, "js": true, "linux": true,
	"netbsd": true, "openbsd": true, "plan9": true, "solaris": true, "wasip1": true,
	"windows": true, "zos": true,
}

var knownArch = map[string]bool{
	"386": true, "amd64": true, "arm": true, "arm64": true, "loong64": true, "mips": true,
	"mips64": true, "mips64le": true, "mipsle": true, "ppc64": true, "ppc64le": true,
	"riscv64": true, "s390x": true, "wasm": true,
}
